def code_for(city: str) -> str:
    """城市名 → 智联码。认不出来就返回空串。"""
    name = (city or "").strip()
    if not name:
        return ""
    if name in CITY_CODES:
        return CITY_CODES[name]
    # 「杭州市」「广西南宁」这种带后缀的
    for key, code in CITY_CODES.items():
        if key in name:
            return code
    return ""


def cities_to_codes(cities) -> List[str]:
    """城市名列表 → 去重后的码列表（保持顺序）。

    **认不出来的城市名直接跳过** —— 不然会塞一个空串，
    抓取时变成 `--city ""` → adapter 报错。
    """
    out, seen = [], set()
    for c in cities or []:
        code = code_for(c)
        if code and code not in seen:
            seen.add(code)
            out.append(code)
    return out


def known_cities() -> List[Dict[str, str]]:
    """给前端用：城市名 + 码，按城市名排。"""
    return [{"name": n, "code": c}
            for n, c in sorted(CITY_CODES.items())]
